"""Deterministic insight rules.

Each rule reads computed evidence + thresholds from rules.yaml and emits a
sentence. Every number in a sentence is taken from the evidence; nothing is
generated by a language model.
"""
from __future__ import annotations

from decimal import Decimal
from typing import Any

from sentinela.engine import D
from sentinela.formatting import money, number, percent, pp

SEVERITY_ORDER = {"alerta": 0, "atencao": 1, "info": 2}


def _i(severity: str, section: str, text: str, rule: str) -> dict[str, str]:
    return {"severity": severity, "section": section, "text": text, "rule": rule}


def build_insights(results: dict[str, Any], checks: list[dict[str, Any]], rules: dict[str, Any]) -> list[dict[str, str]]:
    th = rules["insights"]
    out: list[dict[str, str]] = []

    failed = [c for c in checks if c["status"] == "FALHA"]
    if failed:
        out.append(_i("alerta", "data_quality",
                      f"{len(failed)} checagem(ns) de reconciliação FALHARAM ({', '.join(c['id'] for c in failed)}). "
                      "Conclusões das seções afetadas não são confiáveis até a correção.", "reconciliation_failed"))

    ex = results.get("executive")
    if ex:
        m = ex["metrics"]
        out.append(_i("info", "executive",
                      f"Hold consolidado de {percent(m['hold'])} sobre turnover de {money(m['turnover'])} "
                      f"(GGR {money(m['ggr'])}, {number(m['players'])} players, {number(m['bets'])} apostas).", "exec_summary"))
        if m["ggr"] is not None and D(m["ggr"]) < 0:
            out.append(_i("alerta", "executive",
                          f"GGR NEGATIVO no período ({money(m['ggr'])}): a casa pagou mais do que recebeu.", "negative_ggr"))
        tr = ex["ggr_trend"]
        if tr["slope_per_day"] is not None and tr["r2"] is not None and tr["r2"] >= 0.3:
            direction = "alta" if tr["slope_per_day"] > 0 else "queda"
            out.append(_i("atencao" if direction == "queda" else "info", "executive",
                          f"GGR diário em tendência de {direction} de {money(abs(tr['slope_per_day']))}/dia "
                          f"(R² {number(tr['r2'], 2)}).", "ggr_trend"))
        cut = th["daily_hold_z_alert"]
        odd = [d for d in ex["daily"] if d.get("hold_z") is not None and abs(d["hold_z"]) >= cut]
        if odd:
            worst = max(odd, key=lambda d: abs(d["hold_z"]))
            out.append(_i("atencao", "executive",
                          f"{len(odd)} dia(s) com hold fora do padrão (|z| ≥ {number(cut, 1)}); o mais extremo foi "
                          f"{worst['dia']} com hold {percent(worst['hold'])}.", "daily_hold_outlier"))

    bh = results.get("behavior")
    if bh:
        out.extend(_behavior_insights(bh))

    pv = results.get("providers")
    if pv and pv["providers"]:
        hhi = pv["hhi"]
        sev = ("alerta" if hhi > th["provider_concentration_hhi_alert"]
               else "atencao" if hhi > th["provider_concentration_hhi_attention"] else "info")
        out.append(_i(sev, "providers",
                      f"Concentração de providers HHI {number(hhi)}; líder {pv['top_provider']} com "
                      f"{percent(pv['top_share'])} do turnover.", "provider_hhi"))
        if pv["top_share"] is not None and pv["top_share"] >= Decimal(str(th["top_provider_share_alert"])):
            out.append(_i("alerta", "providers",
                          f"Dependência: {pv['top_provider']} concentra {percent(pv['top_share'])} do turnover "
                          f"(limite {percent(th['top_provider_share_alert'])}).", "provider_dependency"))
        for p in [p for p in pv["providers"] if p["hold_flag"]][:5]:
            out.append(_i("atencao", "providers",
                          f"Provider {p['provider_name']}: hold {percent(p['hold'])} desvia {pp(p['hold_deviation'])} "
                          f"do consolidado com {percent(p['turnover_share'])} do turnover; auditar.", "provider_hold_dev"))

    pr = results.get("players")
    if pr:
        conc = pr["concentration"]
        if conc["top10_turnover_share"] is not None:
            sev = "alerta" if conc["top10_turnover_share"] >= Decimal(str(th["top10_players_turnover_share_alert"])) else "info"
            out.append(_i(sev, "players",
                          f"Top 10 players = {percent(conc['top10_turnover_share'])} do turnover; top 1% = "
                          f"{percent(conc['top1pct_turnover_share'])}; Gini {number(conc['gini_turnover'], 2)}.", "player_concentration"))
        tiers = {t["risk_tier"]: t for t in pr["tiers"]}
        hi, md = tiers.get("alto"), tiers.get("medio")
        if hi:
            out.append(_i("alerta", "players",
                          f"{number(hi['players'])} player(s) em risco ALTO movimentando {money(hi['turnover'])} "
                          f"(GGR {money(hi['ggr'])}). Prioridade de investigação.", "risk_high"))
        if md:
            out.append(_i("atencao", "players",
                          f"{number(md['players'])} player(s) em risco MÉDIO ({money(md['turnover'])} de turnover).", "risk_medium"))
        for f in pr["flag_counts"]:
            if f["players"] and f["flag"] in ("BONUS_ABUSE_PATTERN", "LOW_WAGER_CASHOUT", "HIGH_EXPOSURE"):
                out.append(_i("atencao", "players",
                              f"{f['flag']}: {number(f['players'])} player(s), {money(f['turnover'])} de turnover, "
                              f"ganho líquido dos players {money(f['player_net'])}. {f['description']}", f"flag_{f['flag'].lower()}"))

    af = results.get("affiliates")
    if af:
        for a in [a for a in af["affiliates"] if a["risk_flag"]][:5]:
            out.append(_i("alerta", "affiliates",
                          f"btag {a['btag']}: {percent(a['flagged_rate'])} dos players sinalizados "
                          f"({number(a['risk_multiplier'], 1)}x a média), {number(a['players'])} players. "
                          "Revisar qualidade do tráfego/contrato.", "affiliate_risk"))
        for a in [a for a in af["affiliates"] if a["low_hold_flag"] and not a["risk_flag"]][:3]:
            out.append(_i("atencao", "affiliates",
                          f"btag {a['btag']}: hold {percent(a['hold'])} abaixo de {percent(th['affiliate_low_hold'])} "
                          f"com {money(a['turnover'])} de turnover.", "affiliate_low_hold"))

    gm = results.get("games")
    if gm and gm.get("available"):
        if gm["mode"] == "appearances":
            out.append(_i("info", "games", "top_jogos sem métricas por jogo: ranking por aparições, sem turnover/GGR por jogo.",
                          "games_appearances"))
        hs = gm["hold_stats"]
        band = f"faixa {percent(hs['reference_median'])} ± {percent(hs['tolerance'], 0)}" if hs.get("reference_median") is not None else ""
        for g in [g for g in gm["games"] if g["hold_flag"]][:5]:
            out.append(_i("alerta", "games",
                          f"Jogo {g['game_name']}: hold {percent(g['hold'])} significativamente fora da {band} "
                          f"(z {number(g['band_z'], 2)}, {number(g['clusters'])} players); verificar RTP/configuração.", "game_hold_outlier"))
        for g in [g for g in gm["games"] if g.get("hold_watch")][:5]:
            out.append(_i("atencao", "games",
                          f"Jogo {g['game_name']} em observação: hold {percent(g['hold'])} fora da {band} "
                          f"(z {number(g['band_z'], 2)}), ainda sem significância para alerta; acompanhar com mais dados.", "game_hold_watch"))

    pay = results.get("payments")
    if pay:
        m = pay["metrics"]
        wd = m["withdrawal_to_deposit"]
        out.append(_i("info", "payments",
                      f"Depósitos {money(m['deposits'])}, saques {money(m['withdrawals'])}, "
                      f"líquido {money(m['net_deposits'])}; FTDs {number(m['ftd_players'])}.", "payments_summary"))
        if wd is not None and wd >= Decimal(str(th["withdrawal_to_deposit_alert"])):
            out.append(_i("alerta", "payments", f"Saques = {percent(wd)} dos depósitos: pressão de caixa.", "cash_pressure"))
        for label, key in (("depósitos", "deposit_approval_rate"), ("saques", "withdrawal_approval_rate")):
            rate = m[key]
            if rate is not None and rate < Decimal(str(th["payment_approval_rate_attention"])):
                out.append(_i("atencao", "payments", f"Taxa de aprovação de {label} em {percent(rate)}.", f"approval_{key}"))

    cl = results.get("clients")
    if cl:
        m = cl["metrics"]
        txt = f"{number(m['signups'])} cadastros no período; {percent(m['active_rate'])} jogaram cassino"
        if m["ftd_rate"] is not None:
            txt += f"; conversão cadastro→FTD {percent(m['ftd_rate'])}"
        out.append(_i("info", "clients", txt + ".", "clients_summary"))

    out.sort(key=lambda i: SEVERITY_ORDER[i["severity"]])
    return out


def _behavior_insights(bh: dict[str, Any]) -> list[dict[str, str]]:
    out: list[dict[str, str]] = []
    lc = {r["lifecycle"]: r for r in bh["lifecycle"]}
    n = bh["universe"]
    active = lc.get("ativo")
    if active:
        out.append(_i("info", "behavior",
                      f"{number(active['players'])} de {number(n)} players ativos nos últimos 7 dias ({percent(active['share'])}), "
                      f"responsáveis por {percent(active['deposit_share'])} dos depósitos do período.", "behavior_active"))
    cooling = [lc[k] for k in ("esfriando", "em_risco") if k in lc]
    if cooling:
        players = sum(r["players"] for r in cooling)
        deps = sum((D(r["deposits"]) for r in cooling), D(0))
        out.append(_i("atencao", "behavior",
                      f"{number(players)} players esfriando/em risco (8–30 dias sem jogar) depositaram {money(deps)} no período: "
                      "receita recuperável com ação de retenção.", "behavior_cooling"))
    seg = {sg["id"]: sg for sg in bh["segments"]}
    hot = seg.get("anti_churn_high")
    if hot and hot["players"]:
        out.append(_i("alerta", "behavior",
                      f"Alto valor esfriando: {number(hot['players'])} players com {money(hot['lifetime_deposits'])} de depósitos "
                      f"históricos ({number(hot['eligible'])} elegíveis para campanha após supressão).", "behavior_high_value_cooling"))
    tiers = {t["value_tier"]: t for t in bh["value_tiers"]["tiers"]}
    high = tiers.get("high")
    if high:
        out.append(_i("info", "behavior",
                      f"Faixa alta ({number(high['players'])} players, {percent(high['share'])} da base) concentra "
                      f"{percent(high['deposit_share'])} dos depósitos e {percent(high['ggr_share'])} do GGR.", "behavior_value_concentration"))
    nftd = lc.get("cadastrado_sem_ftd")
    if nftd and nftd["players"]:
        out.append(_i("atencao", "behavior",
                      f"{number(nftd['players'])} cadastrados nunca depositaram ({percent(nftd['share'])} da base).", "behavior_no_ftd"))
    rh = bh.get("rhythm") or {}
    if rh.get("payday_lift") is not None:
        lift = rh["payday_lift"]
        txt = (f"{percent(rh['payday_share'])} dos depósitos caem nas janelas de payday, que são "
               f"{percent(rh['payday_calendar_share'])} dos dias (lift {number(lift, 2)}x).")
        out.append(_i("info", "behavior", txt, "behavior_payday"))
    if bh["suppression"]["players"]:
        out.append(_i("info", "behavior",
                      f"{number(bh['suppression']['players'])} players suprimidos de campanhas ({bh['suppression']['label']}).",
                      "behavior_suppression"))
    return out
